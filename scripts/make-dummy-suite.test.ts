#!/usr/bin/env bun
/**
 * Tests for scripts/make-dummy-suite.ts.
 *
 * What needs proving is the fixture's SHAPE CONTRACT — the parts a battery reads
 * and no one can eyeball at a glance: which file the trace's deepest frame names,
 * that a trace line number is where the code actually sits, and that the planted
 * failure really fails. A generator that silently emitted the inline shape, or a
 * stale line number, would send a session looking somewhere else and quietly
 * invalidate a diagnosis cell — which is the whole job of the knob tested here.
 *
 * Generation writes to a temp dir and the knobs below hold the suite at six tiny
 * tests, so the file runs in well under a second and never touches the repo.
 *
 * node:test rather than bun:test, matching extension/index.test.ts: these run
 * under both runners with @types/node alone.
 *
 * BACKWARD-EQUIVALENCE CONTRACT (mirrors the header of make-dummy-suite.ts)
 * ------------------------------------------------------------------------
 * The generator's recorded fixtures are pinned BEHAVIOURALLY, never by bytes.
 *   1. For each recorded fixture and its recorded knobs, the generator MUST keep
 *      reproducing the behaviour that defines the fixture: the file count, the
 *      total test count, the failing test's NAME (never its line), the assertion
 *      kind, and — for a cause-module fixture — a trace whose deepest frame is a
 *      file other than the failing one. The workload shape is pinned the same
 *      way: the sleeps' duration class and the log volume's order of magnitude.
 *      A change to any of these is what must fail this test — it means the
 *      fixture a cell was measured against is no longer the fixture it claims.
 *   2. A pure byte change — a blank line, an import reorder, a comment — alters
 *      no behaviour, so it MUST NOT fail. The afb2bd1 blank-line drift is the
 *      precedent: it moved every recorded hash and invalidated no reported number.
 *   3. Adding a fixture means adding a row to RECORDED_FIXTURES below with its
 *      exact knobs and its behavioural facts.
 *
 * The recorded hashes in the table are DOCUMENTED HISTORY, not a gate. Each is
 * the fixture's files sorted by path, contents concatenated, sha1, first 16 hex
 * — computed at the fixture's RECORDED ABSOLUTE PATH (the generated files embed
 * their own out-dir in the failure's stack trace, so a hash means nothing without
 * that path). The test prints a NOTE when the regenerated bytes differ from a
 * recorded hash, so drift stays visible without being an error: a record's cited
 * hash may legitimately be stale while the behaviour it stood for is unchanged.
 * When a difference IS behavioural, the assertions below are what say so.
 *
 * The fixtures were generated at different generator revisions (red-tail and
 * equiv predate afb2bd1; long-buried and trace-root were generated at it), which
 * is why their recorded hashes are not interchangeable descriptions of "the
 * fixture" — the behavioural facts below are.
 */
