/** The first integer captured by `pattern`, failing the test if it is absent. */
function matchInt(text: string, pattern: RegExp): number {
  const match = text.match(pattern);
  assert.ok(match, `expected to find ${pattern} in the generated fixture`);
  return Number(match[1]);
}

/**
 * The behavioural facts of a generated fixture, read back from its source: what
 * the contract pins, as opposed to the bytes it happens to be written in. The
 * failing test's name, the total test count and the file count come from the
 * fixture's own output text (its failure block and summary), not from arithmetic
 * over the knobs, so a generator that stopped emitting them would fail here.
 */
interface FixtureFacts {
  files: number;
  tests: number;
  failingTest: string;
  assertKind: string;
  sleepMs: number;
  linesPerTest: number;
  failingFile: string;
  deepestFrameFile: string;
}

function fixtureFacts(outDir: string): FixtureFacts {
  const names = readdirSync(outDir).sort();
  const partFiles = names.filter((name) => /^part-\d+\.test\.ts$/.test(name));
  assert.ok(partFiles.length > 0, "the generator emitted no part files");
  const texts = names.map((name) => readFileSync(join(outDir, name), "utf8"));
  const all = texts.join("\n");

  // The total is files x the loop bound each part file declares; the fixture's
  // own summary must agree with that arithmetic, so neither can drift silently.
  const perFile = matchInt(
    readFileSync(join(outDir, partFiles[0]), "utf8"),
    /for \(let k = 1; k <= (\d+); k\+\+\)/,
  );
  const files = partFiles.length;
  const tests = files * perFile;
  const summary = all.match(/load run summary: (\d+) files, (\d+) tests/);
  assert.ok(summary, "the generated suite must declare its own size");
  assert.equal(Number(summary[1]), files, "summary file count vs generated files");
  assert.equal(Number(summary[2]), tests, "summary test count vs files x per-file");

  // The failing test's NAME — the identity a record quotes — from its failure block.
  const failure = all.match(/load part (\d+) > step (\d+)/);
  assert.ok(failure, "the planted failure must name its test");
  const failingFile = `part-${failure[1]}.test.ts`;

  // The assertion kind: a real assertion failure, not a terse stub.
  assert.match(
    all,
    /AssertionError \[ERR_ASSERTION\]: Expected values to be strictly deep-equal/,
  );
  assert.match(all, /assert\.deepEqual\(/);
  const assertKind = "assert.deepEqual";

  // The trace shape. A cause-module fixture's deepest frame is the module (a file
  // other than the failing test); the inline shape's is the failing test itself.
  const harness = names.find((name) => name === "harness.ts");
  if (harness) {
    assert.match(
      readFileSync(join(outDir, harness), "utf8"),
      /at loadStep \(/,
      "the cause module must contribute the deepest frame",
    );
  } else {
    assert.match(
      readFileSync(join(outDir, failingFile), "utf8"),
      /at TestContext\.<anonymous> \(/,
      "the inline shape's deepest frame must name the failing test",
    );
  }

  return {
    files,
    tests,
    failingTest: `load part ${failure[1]} > step ${failure[2]}`,
    assertKind,
    sleepMs: matchInt(all, /setTimeout\(resolve, (\d+)\)/),
    linesPerTest: matchInt(all, /for \(let line = 1; line <= (\d+); line\+\+\)/),
    failingFile,
    deepestFrameFile: harness ?? failingFile,
  };
}

/**
 * The documented hash, computed the way the records state it: files sorted by
 * path, contents concatenated, sha1, first 16 hex. The scratch out-dir path is
 * normalised back to the recorded path first, because the generated files embed
 * their own out-dir path in the failure's stack trace. Reported as history only.
 */
function hashFixture(outDir: string, recordedPath: string): string {
  const files = readdirSync(outDir)
    .map((name) => join(outDir, name))
    .sort();
  const hash = createHash("sha1");
  for (const file of files) {
    hash.update(readFileSync(file, "utf8").split(outDir).join(recordedPath));
  }
  return hash.digest("hex").slice(0, 16);
}

test("recorded fixtures: each regenerates with the behaviour the contract pins", () => {
  for (const fixture of RECORDED_FIXTURES) {
    const where = fixture.name;
    const outDir = join(root, `recorded-${fixture.name}`);
    const result = spawnSync("bun", ["run", script], {
      encoding: "utf8",
      env: { ...process.env, DUMMY_OUT_DIR: outDir, ...fixture.knobs },
    });
    assert.equal(result.status, 0, `${where}: ${result.stderr}`);

    const facts = fixtureFacts(outDir);

    // The behaviour that makes it THIS fixture — a different failing test, a
    // different count or an altered trace shape is a different fixture.
    assert.equal(facts.files, fixture.files, `${where}: file count moved`);
    assert.equal(facts.tests, fixture.tests, `${where}: total test count moved`);
    assert.equal(
      facts.failingTest,
      fixture.failingTest,
      `${where}: the failing test's name moved`,
    );
    assert.equal(
      facts.assertKind,
      fixture.assertKind,
      `${where}: the assertion kind moved`,
    );
    assert.equal(facts.sleepMs, fixture.sleepMs, `${where}: the sleep knob moved`);
    assert.equal(
      facts.linesPerTest,
      fixture.linesPerTest,
      `${where}: the log density moved`,
    );

    // The workload shape a cell's numbers are comparable within.
    assert.equal(
      durationClass((facts.sleepMs * facts.tests) / 1000),
      fixture.durationClass,
      `${where}: the duration class the sleeps imply moved`,
    );
    assert.equal(
      volumeClass(facts.tests * facts.linesPerTest),
      fixture.volumeClass,
      `${where}: the log-volume order of magnitude moved`,
    );

    // The trace shape a diagnosis cell reads: for a cause-module fixture the
    // deepest frame must be a file OTHER than the failing test.
    if (fixture.causeModule) {
      assert.equal(
        facts.deepestFrameFile,
        "harness.ts",
        `${where}: the deepest frame must be the cause module`,
      );
      assert.notEqual(
        facts.deepestFrameFile,
        facts.failingFile,
        `${where}: the deepest frame must not be the failing test`,
      );
    } else {
      assert.equal(
        facts.deepestFrameFile,
        facts.failingFile,
        `${where}: the inline shape's deepest frame is the failing test`,
      );
    }

    // Bytes are documented history, not a gate: a difference is a NOTE. The
    // behaviour assertions above are what fail when the fixture actually changed.
    const regenerated = hashFixture(outDir, fixture.recordedPath);
    if (regenerated !== fixture.recordedSha) {
      console.log(
        `note: ${where} regenerated to ${regenerated}, not the recorded ` +
          `${fixture.recordedSha}. The bytes differ; the behaviour above is ` +
          `unchanged.` +
          (fixture.recordNote ? ` (${fixture.recordNote})` : ""),
      );
    }

    // A cheap fixture is also RUN, so the facts above are confirmed against the
    // real run, not only the generated source. long-buried is left to the source
    // assertions: its recorded sleeps make it a three-minute run, which no unit
    // test should pay for.
    if ((facts.sleepMs * facts.tests) / 1000 < 5) {
      const run = spawnSync("bun", ["test", outDir], { encoding: "utf8" });
      const output = `${run.stdout ?? ""}\n${run.stderr ?? ""}`;
      assert.notEqual(
        run.status,
        0,
        `${where}: the planted failure must fail the run`,
      );
      assert.match(
        output,
        new RegExp(`\\(fail\\) ${fixture.failingTest}`),
        `${where}: the run must report the expected failing test`,
      );
      assert.match(
        output,
        new RegExp(
          `Ran ${fixture.tests} tests across ${fixture.files} files`,
        ),
        `${where}: the run must report the expected size`,
      );
      assert.match(
        output,
        /operator: "deepStrictEqual"/,
        `${where}: the run must fail a deep-equality assertion`,
      );
      if (fixture.causeModule) {
        assert.match(
          output,
          /at loadStep \(.*harness\.ts:\d+:\d+\)/,
          `${where}: the run's deepest frame must name the cause module`,
        );
      } else {
        assert.match(
          output,
          new RegExp(`at .*${facts.failingFile}:\\d+:\\d+`),
          `${where}: the run's deepest frame must name the failing test`,
        );
      }
    }
  }
});
